#!/usr/bin/env python3
"""Pre-render the in-game overlay's text as 8-bit alpha masks.

The kernel half (experimental/kernel/vitaos_k.c) has no font engine, so every
label is rendered here with the Inter font VitaOS uses:

    python3 tools/make_overlay_assets.py > experimental/kernel/overlay_assets.h

The method is the dev bridge's vaoverlay (i-ha/agent-service/tools).
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONTS = Path(__file__).resolve().parents[1] / "assets"
REG, BOLD = FONTS / "Inter-Regular.ttf", FONTS / "Inter-Bold.ttf"

LABELS = [  # (C name, text, font, size)
    ("t_title", "VitaOS", BOLD, 22),
    ("t_resume", "Resume", BOLD, 21),
    ("t_volume", "Volume", BOLD, 21),
    ("t_bright", "Brightness", BOLD, 21),
    ("t_close", "Close game", BOLD, 21),
    ("t_footer", "X select     O or PS resume     left / right change", REG, 14),
]


def mask(text, path, size):
    f = ImageFont.truetype(str(path), size)
    l, t, r, b = f.getbbox(text)
    asc, desc = f.getmetrics()
    w, h = max(1, r - min(l, 0) + 2), asc + desc
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((-min(l, 0) + 1, 0), text, font=f, fill=255)
    return w, h, im.tobytes()


print("/* Generated by tools/make_overlay_assets.py; do not edit by hand. */")
print("#ifndef OVERLAY_ASSETS_H\n#define OVERLAY_ASSETS_H")
print("typedef struct { int w, h; const unsigned char *px; } Mask;")
for name, text, path, size in LABELS:
    w, h, data = mask(text, path, size)
    print("static const unsigned char %s_px[%d] = {" % (name, len(data)))
    for i in range(0, len(data), 40):
        print("  " + ",".join(str(x) for x in data[i:i + 40]) + ",")
    print("};")
    print("static const Mask %s = {%d, %d, %s_px};" % (name, w, h, name))
print("#endif")
